import type { DownloadableExcelPractice, XlsxCellSpec } from '../utils/xlsxGenerator';

interface CompactPracticeSeed {
  title: string;
  functionTag: string;
  prompt: string;
  hint: string;
  targetCell: string;
  expectedResult: string;
  headers: Array<string | number>;
  rows: Array<Array<string | number>>;
  targetPromptText?: string;
  colWidths?: number[];
  stylesByCol?: Array<'normal' | 'number' | 'currency' | 'percent'>;
}

function buildCells(seed: CompactPracticeSeed): XlsxCellSpec[] {
  const cells: XlsxCellSpec[] = [];
  seed.headers.forEach((h, colIdx) => {
    const colLetter = String.fromCharCode(65 + colIdx);
    cells.push({ ref: `${colLetter}5`, value: h, style: 'header' });
  });

  seed.rows.forEach((row, rIdx) => {
    const rowNum = 6 + rIdx;
    row.forEach((val, colIdx) => {
      const colLetter = String.fromCharCode(65 + colIdx);
      const ref = `${colLetter}${rowNum}`;
      const isTarget = ref.toUpperCase() === seed.targetCell.toUpperCase();
      if (isTarget) {
        cells.push({
          ref,
          value: seed.targetPromptText ?? 'Escribe tu fórmula aquí',
          style: 'target',
        });
      } else if (typeof val === 'number') {
        const colStyle = seed.stylesByCol?.[colIdx] ?? 'number';
        cells.push({ ref, value: val, style: colStyle });
      } else {
        cells.push({
          ref,
          value: val,
          style: colIdx === 0 && rIdx === seed.rows.length - 1 ? 'label' : 'normal',
        });
      }
    });
  });

  // Ensure targetCell exists even if outside initial grid rows
  const alreadyHasTarget = cells.some(
    (c) => c.ref.toUpperCase() === seed.targetCell.toUpperCase()
  );
  if (!alreadyHasTarget) {
    cells.push({
      ref: seed.targetCell.toUpperCase(),
      value: seed.targetPromptText ?? 'Escribe tu fórmula aquí',
      style: 'target',
    });
  }

  return cells;
}

function makePack(lessonId: string, seeds: CompactPracticeSeed[]): DownloadableExcelPractice[] {
  return seeds.map((s, idx) => {
    const num = 11 + idx;
    return {
      id: `${lessonId}-xlsx-${num}`,
      number: num,
      sheetName: `Practica_${num}`,
      title: s.title,
      functionTag: s.functionTag,
      prompt: s.prompt,
      hint: s.hint,
      targetCell: s.targetCell,
      expectedResult: s.expectedResult,
      colWidths: s.colWidths ?? s.headers.map(() => 18),
      cells: buildCells(s),
    };
  });
}

